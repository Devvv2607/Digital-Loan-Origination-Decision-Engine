"""Seed R2 (credit score) thresholds from the credit-risk cut-off project's approval rate.

The reference project's scorecard (points scale, base 600 at 50:1 odds, PDO 20) chose a
535-point cut-off that approved 88.2% of its held-out test set. That scale is NOT the
simulated 300-900 bureau score used here, so the cut-off itself cannot be transferred.
This script only reuses the *approval rate* as a scenario:

  approve_threshold = bureau score at the (1 - 0.882) quantile of the mock bureau's
                      population distribution  -> the top 88.2% pass R2
  refer_floor       = score at the (1 - 0.882 - 0.05) quantile -> the next 5% are referred

It writes backend/policy/seed_policy.json. It does not establish equivalent risk and
does not reproduce the reference project's 5.9% payment-difficulty rate (this
simulation has no repayment outcomes).

Usage (from the repo root):
  backend/.venv/Scripts/python scripts/seed_policy_from_cutoff.py
  ... --simulation-results reports/simulation_results.csv   # step 4, after Phase 6
"""

import argparse
import csv
import json
import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from app.integrations.mock.population import SCORE_DISTRIBUTION, score_from_uniform  # noqa: E402

TEMPLATE = ROOT / "backend" / "policy" / "policy_template.json"
OUTPUT = ROOT / "backend" / "policy" / "seed_policy.json"

SOURCE = (
    "Illustrative calibration to the 88.2% approval-rate scenario from the credit-risk "
    "cut-off project; does not establish equivalent risk."
)
REFERENCE_MODEL = {
    "description": "Logistic-regression points scorecard on Home Credit data (separate project)",
    "repository": "https://github.com/Devvv2607/Credit-Risk-Segmentation-Approval-Cut-off-Strategy",
    "live_site": "https://credit-risk-segmentation-approval-c.vercel.app",
    "score_scale": "Points scorecard: base 600 at 50:1 good:bad odds, 20 points to double the odds (PDO 20)",
    "cutoff_score": 535,
    "approval_rate_on_test_set": 0.882,
    "payment_difficulty_rate_approved": 0.059,
    "payment_difficulty_rate_baseline": 0.0807,
    "note": "Metadata only. The reference score is never compared with or converted into a bureau score.",
}


def calibrate(approval_rate: float, refer_band_width: float, sample_size: int, seed: int) -> dict:
    if not 0 < approval_rate < 1 or not 0 <= refer_band_width < 1 - approval_rate + 1e-12:
        raise ValueError("approval_rate must be in (0,1) and approval_rate + refer_band_width <= 1")
    rng = random.Random(seed)
    scores = sorted(score_from_uniform(rng.random()) for _ in range(sample_size))

    def quantile(q: float) -> int:
        return scores[min(len(scores) - 1, max(0, int(q * len(scores))))]

    approve = quantile(1 - approval_rate)
    floor = quantile(1 - approval_rate - refer_band_width)
    passing = sum(s >= approve for s in scores) / len(scores)
    referred = sum(floor <= s < approve for s in scores) / len(scores)
    return {
        "approve_threshold": approve,
        "refer_floor": floor,
        "achieved_pass_share": round(passing, 4),
        "achieved_refer_share": round(referred, 4),
        "achieved_decline_share": round(1 - passing - referred, 4),
    }


def build_seed(approval_rate: float, refer_band_width: float, sample_size: int, seed: int) -> dict:
    template = json.loads(TEMPLATE.read_text(encoding="utf-8"))
    cal = calibrate(approval_rate, refer_band_width, sample_size, seed)
    for rule in template["rules"]:
        if rule["rule_id"] == "R2":
            rule["parameters"].update(
                approve_threshold=cal["approve_threshold"],
                refer_floor=cal["refer_floor"],
                calibration={
                    "reference_approval_rate": approval_rate,
                    "refer_band_width": refer_band_width,
                    "method": "quantiles of a seeded sample from the mock bureau population distribution",
                },
            )
    return {
        "policy_version": 1,
        "source": SOURCE,
        "reference_model": REFERENCE_MODEL,
        "calibration": {
            "population": f"Normal(mu={SCORE_DISTRIBUTION.mean:g}, sigma={SCORE_DISTRIBUTION.stdev:g}) clipped to 300-900; NTC excluded",
            "sample_size": sample_size,
            "random_seed": seed,
            "reference_approval_rate": approval_rate,
            "refer_band_width": refer_band_width,
            **cal,
        },
        "rules": template["rules"],
    }


def report_on_simulation(path: Path, approve_threshold: int) -> None:
    """Step 4: approval rates the thresholds actually produce on the 500 synthetic applications."""
    if not path.exists():
        print(f"\nStep 4 skipped: {path} not found. It is generated by scripts/run_simulation.py (Phase 6).")
        return
    with path.open(encoding="utf-8") as fh:
        rows = list(csv.DictReader(fh))
    scored = [r for r in rows if r.get("bureau_score")]
    decided = [r for r in rows if r.get("actual_outcome") in ("APPROVED", "REFERRED", "DECLINED")]
    r2_pass = sum(int(r["bureau_score"]) >= approve_threshold for r in scored)
    approved = sum(r["actual_outcome"] == "APPROVED" for r in decided)
    print(f"\nOn {len(rows)} synthetic applications ({path}):")
    print(f"  R2 pass rate among {len(scored)} scored applicants: {r2_pass / len(scored):.1%}" if scored else "  no scored applicants")
    print(f"  Overall engine approval rate among {len(decided)} decided: {approved / len(decided):.1%}" if decided else "  no decisions")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--approval-rate", type=float, default=0.882)
    parser.add_argument("--refer-band-width", type=float, default=0.05)
    parser.add_argument("--sample-size", type=int, default=200_000)
    parser.add_argument("--seed", type=int, default=882)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    parser.add_argument("--simulation-results", type=Path, default=ROOT / "reports" / "simulation_results.csv")
    parser.add_argument("--report-only", action="store_true",
                        help="recompute and report (step 4), but do not rewrite the seed file")
    args = parser.parse_args()

    seed = build_seed(args.approval_rate, args.refer_band_width, args.sample_size, args.seed)
    cal = seed["calibration"]
    if args.report_only:
        print(f"Report only: {args.output} not rewritten")
    else:
        args.output.write_text(json.dumps(seed, indent=2) + "\n", encoding="utf-8")
        print(f"Wrote {args.output.relative_to(ROOT) if args.output.is_relative_to(ROOT) else args.output}")
    print(f"  Reference approval rate: {args.approval_rate:.1%}; refer band: next {args.refer_band_width:.0%}")
    print(f"  R2 approve_threshold = {cal['approve_threshold']}, refer_floor = {cal['refer_floor']}")
    print(f"  On the {cal['sample_size']:,}-score population sample: pass {cal['achieved_pass_share']:.1%}, "
          f"refer {cal['achieved_refer_share']:.1%}, decline {cal['achieved_decline_share']:.1%}")
    report_on_simulation(args.simulation_results, cal["approve_threshold"])


if __name__ == "__main__":
    main()
